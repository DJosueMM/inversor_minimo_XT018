import argparse
import csv
import json
import re
from pathlib import Path

from analyze_characterization import measurements
from first_order_model import current_per_width
from methodology_model import delay_resistances, inverter_capacitances, positive


ROOT = Path(__file__).resolve().parents[1]


def centered_ratio():
    return current_per_width("n", .9, .9) / current_per_width("p", .9, .9)


def write_rows(path, rows):
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def prepare(ratio):
    positive(ratio, "ratio")
    if ratio < 1:
        raise ValueError("PMOS ratio below 1 requires checking minimum-width rules")
    include = ROOT / "spice_decks" / "methodology_sizes.inc"
    with include.open("w", encoding="ascii", newline="\n") as stream:
        stream.write(
            "* Generated by complete_methodology.py; preserve with each run.\n"
            f".param RATIO={ratio:.12g}\n"
            f".param DC_RATIO={centered_ratio():.12g}\n"
            ".data dc_ratios RATIO\n"
            f"{centered_ratio():.12g}\n{ratio:.12g}\n.enddata\n"
        )
    print(f"Prepared ratio={ratio:.12g}; DC_RATIO={centered_ratio():.12g}")
    print(include)


def main():
    parser = argparse.ArgumentParser(description="Prepare/analyze prescribed-method completion runs.")
    commands = parser.add_subparsers(dest="command", required=True)
    prep = commands.add_parser("prepare")
    prep.add_argument("--ratio", type=float, default=2.)
    analyze = commands.add_parser("analyze")
    analyze.add_argument("results", type=Path)
    caps = commands.add_parser("capacitances")
    caps.add_argument("--ratio", type=float, default=2.)
    args = parser.parse_args()
    if args.command == "prepare":
        prepare(args.ratio)
        return
    if args.command == "capacitances":
        print(json.dumps(inverter_capacitances(args.ratio), indent=2))
        return
    results = args.results
    for name in ("methodology_dc", "methodology_fanout", "methodology_fo1"):
        listing = (results / f"{name}.lis").read_text()
        if ("job concluded" not in listing.lower()
                or any(token in listing.lower() for token in
                       ("**error", "**warning", "job aborted", "failed"))):
            raise ValueError(f"Run requires inspection before analysis: {name}")
    sizes = (results / "methodology_sizes.inc").read_text()
    print("Archived run sizes:\n" + sizes)
    fanout = measurements(results / "methodology_fanout.mt0.csv")
    if len(fanout) != 1:
        raise ValueError("Expected one fixed-ratio fanout run")
    extraction = delay_resistances(fanout[0])
    archived_ratio = re.search(r"(?im)^\.param RATIO=([0-9.eE+-]+)\s*$", sizes)
    if not archived_ratio or abs(float(archived_ratio[1]) - extraction["ratio"]) > 1e-7:
        raise ValueError("Archived parameter include and measured ratio do not agree")
    dc = measurements(results / "methodology_dc.ms0.csv")
    if len(dc) != 2:
        raise ValueError("Expected analytical and current-iteration DC checks")
    if not any(abs(row["ratio_used"] - centered_ratio()) < 1e-7 for row in dc):
        raise ValueError("DC results omit the analytically calculated ratio")
    fo1 = measurements(results / "methodology_fo1.mt0.csv")
    if len(fo1) != 1 or abs(fo1[0]["ratio_used"] - extraction["ratio"]) > 1e-7:
        raise ValueError("FO1 and fanout extraction use different sizes")
    if not any(abs(row["ratio_used"] - extraction["ratio"]) < 1e-7 for row in dc):
        raise ValueError("DC and transient sizes are inconsistent")
    output = results / "analisis_metodologia"
    output.mkdir(exist_ok=True)
    write_rows(output / "extraccion.csv", [extraction])
    cap_rows = []
    for ratio in (extraction["ratio"], extraction["proposed_ratio"]):
        caps = inverter_capacitances(ratio)
        for kind in ("n", "p"):
            cap_rows.append({"ratio": ratio, "device": kind, **caps[kind]})
    write_rows(output / "capacitancias.csv", cap_rows)
    print(json.dumps(extraction, indent=2))
    print("FO1 measured:", fo1[0])
    print("DC measured:", dc)
    print("Not converged automatically: inspect proposed ratio and rerun prepare --ratio as needed.")
    print("Inspect input/output 20-80% slopes; no ideal input is used for resistance extraction.")
    print("First-order model assumptions are documented; this is not BSIM capacitance reconstruction.")


if __name__ == "__main__":
    main()
